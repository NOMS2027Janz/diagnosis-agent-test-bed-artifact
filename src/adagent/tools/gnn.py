# ---------------------------------------------------------------------- the local graph
@dataclass
class LocalGraph:
    nodes: list = field(default_factory=list)          # node ids
    types: list = field(default_factory=list)
    index: dict = field(default_factory=dict)
    edges: list = field(default_factory=list)          # (edge type, i, j)
    streams: dict = field(default_factory=dict)        # node id -> {feature name: (observable, lake element)}

    def add(self, nid: str, t: str) -> int:
        if nid not in self.index:
            self.index[nid] = len(self.nodes)
            self.nodes.append(nid)
            self.types.append(t)
            self.streams[nid] = {}
        return self.index[nid]


def _elid(e) -> str:
    return e if isinstance(e, str) else e.id


def _paths(net: Network, lp) -> list[tuple[str, list[str], str]]:
    """(direction, OMS path, receiving transponder) for both directions of a lightpath."""
    fwd = list(lp.oms_path)
    rn = list(reversed(lp.nodes))
    try:
        rev = [net.oms_between(rn[i], rn[i + 1]) for i in range(len(rn) - 1)]
    except KeyError:
        rev = []
    out = [("fwd", fwd, lp.dst_trx)]
    if rev:
        out.append(("rev", rev, lp.src_trx))
    return out


def build_graph(net: Network, lightpaths: Optional[list[str]] = None) -> LocalGraph:
    g = LocalGraph()
    lps = [net.lightpaths[x] for x in (lightpaths if lightpaths is not None else sorted(net.lightpaths))]
    chain, observed = set(), set()
    for lp in lps:
        for d, path, rx in _paths(net, lp):
            tx = lp.src_trx if d == "fwd" else lp.dst_trx
            prev = g.add(tx, "trx")
            on_path = []
            for oid in path:
                o = net.oms[oid]
                c = g.add(f"conn:{oid}", "conn")
                chain.add((prev, c))
                prev = c
                on_path.append(c)
                members = [c]
                for e in o.elements:
                    i = g.add(_elid(e), "amp" if isinstance(e, Amplifier) or "amp" in _elid(e).rsplit(".", 1)[-1]
                              else "span")
                    chain.add((prev, i))
                    prev = i
                    on_path.append(i)
                    members.append(i)
                w = g.add(f"wss:{oid}|{lp.slot}", "wss")
                chain.add((prev, w))
                prev = w
                on_path.append(w)
                g.streams[f"wss:{oid}|{lp.slot}"].update({
                    "ocm_p": ("ocm_channel_power", f"{o.dst}:{oid}|{lp.slot}"),
                    "ocm_o": ("ocm_osnr", f"{o.dst}:{oid}|{lp.slot}")})
                for m in members:
                    observed.add((m, w))
            r = g.add(rx, "trx")
            chain.add((prev, r))
            g.streams[rx].update({"rx": ("rx_power", rx), "osnr": ("est_osnr", rx), "ber": ("pre_fec_ber", rx),
                                  "dgd": ("dgd", rx)})
            for i in on_path:
                observed.add((i, r))
    for nid, t in zip(g.nodes, g.types):
        if t == "amp":
            g.streams[nid].update({"in": ("amp_input_power", nid), "out": ("amp_output_power", nid)})
    g.edges = [(0, i, j) for i, j in chain] + [(1, j, i) for i, j in chain] + \
              [(2, i, j) for i, j in observed if i != j] + [(3, j, i) for i, j in observed if i != j]
    return g


def _delta(ba, scale):
    """(change, lost, present) from a (before, after) pair of summaries."""
    if ba is None:
        return 0.0, 0.0, 0.0
    b, a = ba
    if b is None or a is None:
        return 0.0, 0.0, 0.0
    if b == -math.inf:
        return 0.0, 0.0, 1.0
    if a == -math.inf:
        return 0.0, 1.0, 1.0
    return max(-5.0, min(5.0, (a - b) / scale)), 0.0, 1.0


def features(g: LocalGraph, readings: dict) -> np.ndarray:
    """readings: (observable, lake element) -> (before, after); missing streams are absent."""
    X = np.zeros((len(g.nodes), N_FEAT))
    for i, (nid, t) in enumerate(zip(g.nodes, g.types)):
        X[i, TYPES.index(t)] = 1.0
        s = g.streams[nid]
        if t == "amp":
            di, li, hi = _delta(readings.get(s["in"]), 4.0)
            do, lo, ho = _delta(readings.get(s["out"]), 4.0)
            X[i, 5:10] = [di, do, li, lo, max(hi, ho)]
        elif t == "trx" and "rx" in s:
            dr, lr, hr = _delta(readings.get(s["rx"]), 4.0)
            dq, lq, hq = _delta(readings.get(s["osnr"]), 4.0)
            db, _, _ = _delta(readings.get(s["ber"]), 1.0)
            dd, _, _ = _delta(readings.get(s["dgd"]), 10.0)
            X[i, 10:17] = [dr, dq, db, dd, max(lr, lq), hr, hq]
        elif t == "wss":
            dp, lp_, hp = _delta(readings.get(s["ocm_p"]), 4.0)
            dq, _, _ = _delta(readings.get(s["ocm_o"]), 4.0)
            X[i, 17:21] = [dp, dq, lp_, hp]
    return X


def adjacency(g: LocalGraph) -> list[np.ndarray]:
    n = len(g.nodes)
    A = [np.zeros((n, n)) for _ in range(N_EDGE_TYPES)]
    for t, i, j in g.edges:
        A[t][j, i] = 1.0                       # message from i to j
    for t in range(N_EDGE_TYPES):
        deg = A[t].sum(1, keepdims=True)
        A[t] = A[t] / np.maximum(deg, 1.0)
    return A


def class_mask(g: LocalGraph) -> np.ndarray:
    M = np.full((len(g.nodes), len(CLASSES)), -1e9)
    M[:, 0] = 0.0
    for i, t in enumerate(g.types):
        for c in VALID[t]:
            M[i, CLASSES.index(c)] = 0.0
    return M


# ---------------------------------------------------------------------- generated training cases
def random_topology(rng: random.Random) -> dict:
    n = rng.randint(2, 6)
    names = [chr(ord("A") + i) for i in range(n)]
    links, k = {}, 0

    def link(a, b):
        nonlocal k
        k += 1
        links[f"L{k}"] = (a, b, rng.uniform(60.0, 520.0))
    for i in range(n - 1):
        link(names[i], names[i + 1])
    if n >= 3 and rng.random() < 0.6:
        link(names[-1], names[0])
    for _ in range(rng.randint(0, max(0, n - 3))):
        a, b = rng.sample(names, 2)
        if not any({a, b} == {x, y} for x, y, _ in links.values()):
            link(a, b)
    return links


def _perturb(net: Network, rng: random.Random) -> None:
    """Record errors: the world the training case is drawn from differs from the records the graph is built from."""
    for a in net.amps.values():
        a.true_nf_db = a.nf_db + rng.gauss(0.0, 0.5)
        a.gain_db += rng.gauss(0.0, 0.2)
    for s in net.spans.values():
        s.true_loss_db_per_km = s.loss_db_per_km * (1.0 + rng.gauss(0.0, 0.03))


def _targets(net: Network, kind: str, rng: random.Random) -> Optional[str]:
    if kind == "span":
        return rng.choice(sorted(net.spans))
    if kind == "conn":
        return rng.choice(sorted(net.oms))
    if kind == "amp":
        return rng.choice(sorted(net.amps))
    if kind == "wss":
        lp = net.lightpaths[rng.choice(sorted(net.lightpaths))]
        return f"{rng.choice(lp.oms_path)}|{lp.slot}"
    if kind == "trx":
        return rng.choice(sorted(net.transponders))
    return None


KIND_OF = {c: t for t, cs in VALID.items() for c in cs if c != "INSTRUMENT_MISREPORT"}


def node_of(mode: str, target: str) -> str:
    k = KIND_OF.get(mode)
    if k == "conn":
        return f"conn:{target}"
    if k == "wss":
        return f"wss:{target}"
    return target


def _snapshot_readings(net: Network, snap, dep: dict) -> dict:
    w = WorldSim(net, deployment=dep)
    out = {}
    for aid, r in snap.amps.items():
        if w.has("amp_power", aid):
            out[("amp_input_power", aid)] = r.input_dbm_per_ch
            out[("amp_output_power", aid)] = r.output_dbm_per_ch
    for r in snap.rx.values():
        if w.has("rx_power", r.trx):
            out[("rx_power", r.trx)] = r.rx_power_dbm
        if w.has("coherent", r.trx):
            lost = not math.isfinite(r.rx_power_dbm)
            out[("est_osnr", r.trx)] = -math.inf if lost else r.osnr_db
            out[("pre_fec_ber", r.trx)] = -math.inf if lost else math.log10(max(r.pre_fec_ber, 1e-30))
            out[("dgd", r.trx)] = -math.inf if lost else r.dgd_ps
    for (oid, slot), (p, o) in snap.ocm.items():
        el = f"{net.oms[oid].dst}:{oid}"
        if w.has("ocm", el):
            out[("ocm_channel_power", f"{el}|{slot}")] = p
            out[("ocm_osnr", f"{el}|{slot}")] = o if p > -math.inf else -math.inf
    return out


def _noise(ob: str) -> float:
    if ob in ("est_osnr", "ocm_osnr"):
        return NOISE["osnr_db"]
    if ob == "pre_fec_ber":
        return 0.05
    if ob == "dgd":
        return 0.3
    return NOISE["power_db"]


def generate_case(seed: int) -> dict:
    """One generated training case: graph, features, labels."""
    rng = random.Random(seed)
    net = build_network(f"gen{seed}", random_topology(rng), seed=seed, n_lightpaths=rng.randint(3, 12))
    _perturb(net, rng)
    dep = {s: rng.choice(SITE_TIERS) for s in {o.src for o in net.oms.values()} | {o.dst for o in net.oms.values()}}
    kinds = [k for k in ("span", "conn", "amp", "wss", "trx")]
    events, labels = [], {}
    n_faults = 0 if rng.random() < 0.08 else 2 if rng.random() < 0.25 else 1
    for _ in range(n_faults):
        k = rng.choices(kinds, weights=[3, 1.5, 3, 1.5, 1.5])[0]
        mode = rng.choice(sorted(c for c in VALID[k] if c != "INSTRUMENT_MISREPORT"))
        tgt = _targets(net, k, rng)
        params = {}
        if mode in RANGES:
            p, lo, hi = RANGES[mode]
            params[p] = math.exp(rng.uniform(math.log(lo), math.log(hi)))
        events.append(Event(mode, tgt, params, onset=0.0))
        labels[node_of(mode, tgt)] = mode
    before = _snapshot_readings(net, evaluate(net), dep)
    after = _snapshot_readings(net, evaluate(net, effects_at(events, 1.0)), dep)
    misreport = None
    if rng.random() < 0.15 or n_faults == 0:
        cands = sorted({el.split("|")[0] for (_, el) in after})
        if cands:
            misreport = rng.choice(cands)
            bias = rng.choice([-1, 1]) * rng.uniform(1.0, 6.0)
            for k2 in list(after):
                ob, el = k2
                if (el == misreport or el.split("|")[0] == misreport) and ob in (
                        "amp_input_power", "amp_output_power", "rx_power", "ocm_channel_power", "est_osnr", "ocm_osnr"):
                    if after[k2] > -math.inf:
                        after[k2] += bias
    readings = {}
    for k2 in before:
        b, a = before[k2], after.get(k2)
        sd = _noise(k2[0])
        if b > -math.inf:
            b += rng.gauss(0.0, sd / math.sqrt(N_BEFORE))
        if a is not None and a > -math.inf:
            a += rng.gauss(0.0, sd / math.sqrt(N_AFTER))
        readings[k2] = (b, a)
    g = build_graph(net)
    if misreport is not None:
        if misreport in g.index:
            labels.setdefault(misreport, "INSTRUMENT_MISREPORT")
        elif ":" in misreport:                     # a channel monitor: its WSS ports
            oid = misreport.split(":", 1)[1]
            for nid in g.nodes:
                if nid.startswith(f"wss:{oid}|"):
                    labels.setdefault(nid, "INSTRUMENT_MISREPORT")
    y = np.zeros(len(g.nodes), dtype=int)
    for nid, m in labels.items():
        if nid in g.index:
            y[g.index[nid]] = CLASSES.index(m)
    return {"graph": g, "X": features(g, readings), "y": y, "labels": labels}


# ---------------------------------------------------------------------- the model
def init_params(hidden: int = 32, layers: int = 3, seed: int = 0) -> dict:
    r = np.random.default_rng(seed)

    def m(a, b):
        return r.normal(0.0, math.sqrt(2.0 / (a + b)), size=(a, b))
    p = {"W0": m(N_FEAT, hidden), "b0": np.zeros(hidden), "Wo": m(hidden, len(CLASSES)), "bo": np.zeros(len(CLASSES))}
    for l in range(layers):
        p[f"Ws{l}"] = m(hidden, hidden)
        p[f"b{l + 1}"] = np.zeros(hidden)
        for t in range(N_EDGE_TYPES):
            p[f"We{l}_{t}"] = m(hidden, hidden)
    p["_layers"] = layers
    return p


def forward(p: dict, X, A, M):
    h = anp.maximum(0.0, anp.dot(X, p["W0"]) + p["b0"])
    for l in range(int(p["_layers"])):
        z = anp.dot(h, p[f"Ws{l}"]) + p[f"b{l + 1}"]
        for t in range(N_EDGE_TYPES):
            z = z + anp.dot(anp.dot(A[t], h), p[f"We{l}_{t}"])
        h = h + anp.maximum(0.0, z)
    logits = anp.dot(h, p["Wo"]) + p["bo"] + M
    return logits - anp.max(logits, axis=1, keepdims=True)


def log_softmax(z):
    return z - anp.log(anp.sum(anp.exp(z), axis=1, keepdims=True))


def _loss(p, batch, pos_weight):
    tot = 0.0
    for X, A, M, y in batch:
        lp = log_softmax(forward(p, X, A, M))
        w = np.where(y > 0, pos_weight, 1.0)
        tot = tot - anp.sum(w * lp[np.arange(len(y)), y]) / np.sum(w)
    return tot / len(batch)


def train(cases: list[dict], epochs: int = 25, batch: int = 16, lr: float = 3e-3, pos_weight: float = 20.0,
          hidden: int = 32, layers: int = 3, seed: int = 0, log=print, checkpoint: Optional[Path] = None) -> dict:
    """Adam on mini-batches of graphs. Adjacency is built per batch (memory); with checkpoint, the state is saved
    after each epoch and a run resumes from it."""
    p = init_params(hidden, layers, seed)
    keys = [k for k in p if not k.startswith("_")]
    m = {k: np.zeros_like(p[k]) for k in keys}
    v = {k: np.zeros_like(p[k]) for k in keys}
    g = grad(lambda q, b: _loss({**q, "_layers": layers}, b, pos_weight))
    rng = np.random.default_rng(seed)
    step, start = 0, 0
    if checkpoint is not None and Path(checkpoint).exists():
        st = np.load(checkpoint, allow_pickle=True).item()
        p.update(st["p"]), m.update(st["m"]), v.update(st["v"])
        step, start = st["step"], st["epoch"]
        for _ in range(start):
            rng.permutation(len(cases))
        log(f"resumed after epoch {start}")
    for ep in range(start, epochs):
        order = rng.permutation(len(cases))
        tot = 0.0
        for s in range(0, len(order), batch):
            b = [(cases[i]["X"], adjacency(cases[i]["graph"]), class_mask(cases[i]["graph"]), cases[i]["y"])
                 for i in order[s:s + batch]]
            q = {k: p[k] for k in keys}
            gr = g(q, b)
            step += 1
            for k in keys:
                m[k] = 0.9 * m[k] + 0.1 * gr[k]
                v[k] = 0.999 * v[k] + 0.001 * gr[k] ** 2
                p[k] = p[k] - lr * (m[k] / (1 - 0.9 ** step)) / (np.sqrt(v[k] / (1 - 0.999 ** step)) + 1e-8)
            tot += float(_loss(p, b, pos_weight)) * len(b)
        log(f"epoch {ep + 1}/{epochs} loss {tot / len(cases):.4f}")
        if checkpoint is not None:
            np.save(checkpoint, {"p": {k: p[k] for k in keys}, "m": m, "v": v, "step": step, "epoch": ep + 1},
                    allow_pickle=True)
            Path(str(checkpoint) + ".npy").replace(checkpoint) if Path(str(checkpoint) + ".npy").exists() else None
    return p


def node_probs(p: dict, g: LocalGraph, X) -> np.ndarray:
    z = forward(p, X, adjacency(g), class_mask(g))
    e = np.exp(z)
    return e / e.sum(1, keepdims=True)


def evaluate_ranking(p: dict, cases: list[dict], ks=(1, 3, 5, 10)) -> dict:
    """Recall at k of the true (element, class) among every (element, class) the model can score, on held-out cases;
    for a case with several faults each counts separately."""
    hits = {k: 0 for k in ks}
    n, pools = 0, []
    for c in cases:
        g = c["graph"]
        P = node_probs(p, g, c["X"])
        pairs = [(P[i, CLASSES.index(cl)], nid, cl) for i, (nid, t) in enumerate(zip(g.nodes, g.types))
                 for cl in VALID[t]]
        pairs.sort(key=lambda x: -x[0])
        pools.append(len(pairs))
        rank = {(nid, cl): r for r, (_, nid, cl) in enumerate(pairs)}
        for nid, cl in c["labels"].items():
            if (nid, cl) in rank:
                n += 1
                for k in ks:
                    hits[k] += rank[(nid, cl)] < k
    return {"cases": len(cases), "faults": n, "mean_pool": float(np.mean(pools)) if pools else 0.0,
            **{f"recall_at_{k}": hits[k] / max(n, 1) for k in ks}}


def save(p: dict, meta: dict, name: str = "ranker") -> Path:
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    np.savez(MODEL_DIR / f"{name}.npz", **{k: v for k, v in p.items() if not k.startswith("_")},
             _layers=np.array(p["_layers"]))
    (MODEL_DIR / f"{name}.json").write_text(json.dumps(meta, indent=1))
    return MODEL_DIR / f"{name}.npz"


def load(name: str = "ranker") -> tuple[dict, dict]:
    z = np.load(MODEL_DIR / f"{name}.npz")
    p = {k: z[k] for k in z.files}
    p["_layers"] = int(p["_layers"])
    return p, json.loads((MODEL_DIR / f"{name}.json").read_text())


# ---------------------------------------------------------------------- the tool at diagnosis
class GNNRanker:
    """Orders the ledger's candidates by the model's score of their element and fault class."""
    name, version = "gnn.ranker", "0.1"

    def __init__(self, substrate, sources, onset: float, model: str = "ranker", frame=None):
        from .twin import GraphTwin, Windows, twin_network
        self.sub, self.kg = substrate, substrate.kg
        self.p, self.meta = load(model)
        design = (sources.practice.get("line_design") or {}).get("design", {})
        self.net = twin_network(self.kg, design)             # the records' network: structure only
        stub = type("Obs", (), {})()
        stub.sub, stub.win, stub._summarise = substrate, Windows.around(float(onset), float(substrate.now)), \
            GraphTwin._summarise
        stub.onset = float(onset)
        obs = GraphTwin._observed(stub)                       # the lake summaries the twin is compared with
        self.readings = {k: (v.get("b"), v.get("a")) for k, v in obs.cont.items()}
        self.frame = frame
        self.lightpaths = self._region()
        self.g = build_graph(self.net, self.lightpaths)
        self.P = node_probs(self.p, self.g, features(self.g, self.readings)) if self.g.nodes else None

    def _changed(self, key) -> bool:
        ba = self.readings.get(key)
        if not ba or ba[0] is None or ba[1] is None:
            return False
        b, a = ba
        if (b == -math.inf) != (a == -math.inf):
            return True
        if b == -math.inf:
            return False
        return abs(a - b) > (1.0 if key[0] in ("est_osnr", "ocm_osnr") else 0.3 if key[0] != "dgd" else 2.0)

    def _region(self) -> list[str]:
        """Lightpaths touching the elements whose streams changed: the frame's change symptoms when a frame is given
        (the framer's statistical test, as the agent sees it), otherwise a fixed threshold on the change. Ranked by
        how many changed elements each touches, at most REGION_MAX."""
        if self.frame is not None:
            changed = {sy.element.split("|")[0] for sy in self.frame.symptoms if sy.kind in ("change", "pm")}
        else:
            changed = {el.split("|")[0] for (ob, el) in self.readings if self._changed((ob, el))}
        hits = {}
        for lid, lp in self.net.lightpaths.items():
            n = 0
            for d, path, rx in _paths(self.net, lp):
                els = {rx} | {_elid(e) for oid in path for e in self.net.oms[oid].elements} | \
                      {f"{self.net.oms[oid].dst}:{oid}" for oid in path}
                n = max(n, len(els & changed))
            if n:
                hits[lid] = n
        return sorted(hits, key=lambda k: (-hits[k], k))[:REGION_MAX]

    def in_domain(self) -> bool:
        """The model was trained on lasting changes (before against after). With a frame, it speaks only when some
        change symptom is a level shift or a lost signal; on a transient (excursions only) it abstains."""
        if self.frame is None:
            return True
        return any(sy.kind == "change" and sy.detail.split(" ")[0] in ("level", "lost") for sy in self.frame.symptoms)

    def score_cause(self, mode: str, el: str) -> Optional[float]:
        if self.P is None:
            return None
        if mode == "INSTRUMENT_MISREPORT":
            a = self.kg.g.nodes.get(el, {}) if self.kg.has(el) else {}
            lake = a.get("lake_element", el)
            if lake in self.g.index:
                return float(math.log(max(self.P[self.g.index[lake], CLASSES.index(mode)], 1e-12)))
            if ":" in lake:
                oid = lake.split(":", 1)[1]
                vals = [self.P[i, CLASSES.index(mode)] for nid, i in self.g.index.items()
                        if nid.startswith(f"wss:{oid}|")]
                return float(math.log(max(max(vals), 1e-12))) if vals else None
            return None
        if mode not in KIND_OF:
            return None
        nid = node_of(mode, el)
        if nid not in self.g.index:
            return None
        return float(math.log(max(self.P[self.g.index[nid], CLASSES.index(mode)], 1e-12)))

    def likelihood(self, hyps: list):
        """The model's log-probability of each candidate's (element, fault class), summed over a compound's causes;
        candidates it cannot score are declined (neutral in the ledger); "none of these" takes the best score of an
        (element, fault class) no candidate covers."""
        from ..schemas import LikelihoodPayload, LikelihoodValue
        if not self.in_domain():
            return None
        rp = self.payload(hyps)
        if rp is None:
            return None
        sc = dict(rp.scores)
        none = sc.pop("NONE_OF_THESE", None)
        vals = {h.key(): (LikelihoodValue(log_likelihood=sc[h.key()]) if h.key() in sc else
                          LikelihoodValue(declined=True, decline_reason="not a fault class the model knows"))
                for h in hyps}
        # "none of these" is not scored: the best of many uncovered pairs is biased upward (the maximum of many small
        # probabilities), and on development cases it carried "none of these" past the truth. With no background the
        # ledger gives "none of these", like declined candidates, the term's mean: the GNN reorders the candidates it
        # can score and is silent on causes nobody proposed.
        return LikelihoodPayload(values=vals, background_log_likelihood=None)

    def payload(self, hyps: list):
        from ..schemas import RankerPayload
        scores = {}
        for h in hyps:
            vals = []
            for c in h.causes:
                loc = c.location
                el = loc.element if loc.kind == "element" else getattr(loc, "span", None)
                s = self.score_cause(c.fault_mode, el) if el else None
                if s is None:
                    vals = None
                    break
                vals.append(s)
            if vals:
                scores[h.key()] = sum(vals)
        self._last_scores = scores
        if len(scores) <= RANK_K:
            return None
        # "none of these": the best score of an (element, fault class) that no candidate covers
        covered = set()
        for h in hyps:
            for c in h.causes:
                loc = c.location
                el = loc.element if loc.kind == "element" else getattr(loc, "span", None)
                if el and c.fault_mode in KIND_OF:
                    covered.add((node_of(c.fault_mode, el), c.fault_mode))
                elif el and c.fault_mode == "INSTRUMENT_MISREPORT":
                    a = self.kg.g.nodes.get(el, {}) if self.kg.has(el) else {}
                    lake = a.get("lake_element", el)
                    covered |= {(nid, "INSTRUMENT_MISREPORT") for nid in self.g.index
                                if nid == lake or (":" in lake and nid.startswith(f"wss:{lake.split(':', 1)[1]}|"))}
        best = max((float(math.log(max(self.P[i, CLASSES.index(cl)], 1e-12))) for i, (nid, t) in
                    enumerate(zip(self.g.nodes, self.g.types)) for cl in VALID[t] if (nid, cl) not in covered),
                   default=None)
        if best is not None:
            scores["NONE_OF_THESE"] = best
        order = sorted(scores, key=lambda k: -scores[k])
        recall = min(RECALL_CAP, float(self.meta.get("recall_at_3", 0.5)))
        return RankerPayload(ordering=order, k=RANK_K, recall_at_k=recall,
                             scores={k: float(v) for k, v in scores.items()})
