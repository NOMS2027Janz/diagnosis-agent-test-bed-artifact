"""GNN rankers: general tools trained on generated local topologies, applied unchanged to the network under diagnosis
(spec/CANDIDATE_TOOLS.md A1; "Graph Neural Networks for Anomaly Diagnosis"; "Why Diagnostic GNN Tools Should
Transfer").

Preliminary version (2026-10-17), for the Experiment 2 extension. One model, three use cases of the GNN paper in one
output: soft- and hard-fault localisation (which element, and fibre against amplifier against connector against
WSS against transponder), multiple simultaneous faults (each node is classified on its own, so two faulted nodes can
both score high), and instrument misreports found by disagreement with neighbouring readings (a class of its own).

Graph. One node per element of the region: the input connector of each OMS, each amplifier, each span, the WSS
channel port of each lightpath at the end of each OMS it crosses, and each transponder. Edges of four types: the
signal chain downstream and upstream (connector, booster, span, inline amplifiers, ..., preamplifier, WSS port, next
OMS ... receiving transponder), and an "observed by" relation from every element on a lightpath's path to that
lightpath's receiving transponder and from every element of an OMS to the WSS ports at its end (where the channel
monitor reads), with its reverse. The second relation brings far-end evidence within two hops of every element.

Inputs. Per node: its type, and for the streams it carries the change from before onset to after (amplifier input
and output power; received power, estimated OSNR, log pre-FEC bit error rate and DGD at a receiving transponder;
channel-monitor power and OSNR at a WSS port), with flags for a signal lost and for a stream present at the site's
tier. Changes, not levels: calibration offsets cancel. At diagnosis the changes come from the same lake summaries
the twin is compared with (GraphTwin._observed), so the tool reads exactly what the agent holds.

Training. Generated by the default physics (world version 1) on random local topologies: lines and small meshes of
two to six ROADMs, random span counts and lengths, random lightpaths, random monitoring tiers per site, and random
record errors (per-amplifier noise figure and gain, per-span loss), with instrument noise averaged as over the
before and after windows. Faults: one documented fault mode with a twin scenario, from its documented range; with
probability 0.25 a second; with probability 0.15 an instrument misreport (alone or with a fault). The reference
network is never seen in training.

Output in the ledger, as used in the extension's arms: a likelihood term (GNNRanker.likelihood), like the twin's:
each candidate's log-probability under the model, "none of these" at the best score of an uncovered (element, fault
class), candidates it cannot score declined, tempered by its share of the data held and capped by the ledger. A
top-k ranker term (below, the contract first planned) was tried and set aside: it gives every candidate in the top k
the same boost, so on development case s2132 "none of these", ranked second at a seventh of the truth's probability,
gained as much as the truth; it throws away the model's confidence. The ranker form, kept for reference
(GNNRanker.payload, ledger.add_ranker): candidate hypotheses ordered by the model's score of their
(element, fault class), k = RANK_K, with the recall at k measured on held-out generated cases. "None of these" is
ranked too, by the best score the model gives an (element, fault class) that no candidate covers: without it a ranker
could only redistribute mass among the candidates and, sharing the data held with the twin, would weaken the case
against "none of these". Hypotheses the model
cannot score (modes it does not know, OTN, context, ageing, transients) are left out of its pool, so the term does
not touch them.

Implementation: numpy with autograd (no deep-learning framework is available in the working environment).
"""
